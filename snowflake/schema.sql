-- CommonCart analytical tables (session-scoped copies of Postgres records).
-- Apply with `npm run snowflake:setup` against the configured database/schema.
-- Rows are keyed by session and entity; ENTITY_VERSION guards against older sync events.
CREATE TABLE IF NOT EXISTS OFFERS (
  SESSION_ID STRING NOT NULL,
  OFFER_ID STRING NOT NULL,
  ENTITY_VERSION NUMBER NOT NULL,
  RETAILER STRING,
  SKU STRING,
  PRODUCT_FAMILY STRING,
  PACKAGE_QUANTITY NUMBER,
  TOTAL_CENTS NUMBER,
  BASELINES VARIANT,
  MEMBERSHIP_REQUIRED STRING,
  PICKUP_ZONE STRING,
  PICKUP_WINDOWS ARRAY,
  AVAILABLE BOOLEAN,
  EXPIRES_AT TIMESTAMP_TZ,
  SOURCE_KIND STRING,
  RETRIEVED_AT TIMESTAMP_TZ,
  PRIMARY KEY (SESSION_ID, OFFER_ID)
);

CREATE TABLE IF NOT EXISTS NEEDS (
  SESSION_ID STRING NOT NULL,
  NEED_ID STRING NOT NULL,
  ENTITY_VERSION NUMBER NOT NULL,
  SHOPPER_ID STRING,
  ACCEPTED_OFFER_IDS ARRAY,
  QUANTITY NUMBER,
  MAX_CONTRIBUTION_CENTS NUMBER,
  PICKUP_ZONE STRING,
  PICKUP_WINDOW STRING,
  STATUS STRING,
  CREATED_AT TIMESTAMP_TZ,
  PRIMARY KEY (SESSION_ID, NEED_ID)
);

CREATE TABLE IF NOT EXISTS PROPOSALS (
  SESSION_ID STRING NOT NULL,
  GROUP_ID STRING NOT NULL,
  ENTITY_VERSION NUMBER NOT NULL,
  OFFER_ID STRING,
  STATUS STRING,
  TOTAL_CENTS NUMBER,
  TOTAL_SAVINGS_CENTS NUMBER,
  MEMBER_COUNT NUMBER,
  ALLOCATIONS VARIANT,
  UPDATED_AT TIMESTAMP_TZ,
  PRIMARY KEY (SESSION_ID, GROUP_ID)
);

CREATE TABLE IF NOT EXISTS OPERATIONS (
  SESSION_ID STRING NOT NULL,
  OPERATION_ID STRING NOT NULL,
  ENTITY_VERSION NUMBER NOT NULL,
  GROUP_ID STRING,
  KIND STRING,
  STATUS STRING,
  AMOUNT_CENTS NUMBER,
  PROVIDER_ID STRING,
  UPDATED_AT TIMESTAMP_TZ,
  PRIMARY KEY (SESSION_ID, OPERATION_ID)
);
